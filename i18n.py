def normalize_lang(lang: str) -> str:
    """Возвращает поддерживаемый код языка или язык по умолчанию."""
    if not lang:
        return DEFAULT_LANG
    lang = lang.strip().lower()
    if lang in LANGUAGES:
        return lang
    return DEFAULT_LANG


def t(key: str, lang: str = DEFAULT_LANG, **kwargs) -> str:
    """Перевести ключ. Если ключа нет — вернуть сам ключ.

    Поддерживает форматирование через {placeholder} при наличии kwargs.
    """
    lang = normalize_lang(lang)
    table = TRANSLATIONS.get(lang) or TRANSLATIONS[DEFAULT_LANG]
    value = table.get(key)
    if value is None:
        # fallback на DEFAULT_LANG, затем на сам key
        value = TRANSLATIONS[DEFAULT_LANG].get(key, key)
    if kwargs:
        try:
            return value.format(**kwargs)
        except (KeyError, IndexError):
            return value
    return value


def position_label(position: str, lang: str = DEFAULT_LANG) -> str:
    """Возвращает локализованное название должности.
    Ключ позиции в БД остаётся на русском, отображение переводится.
    """
    if not position:
        return ""
    return t(f"position.{position}", lang)


def role_label(role: str, lang: str = DEFAULT_LANG) -> str:
    """Возвращает локализованное название роли пользователя."""
    return t(f"role.{role}", lang)


def status_label(label_key: str, lang: str = DEFAULT_LANG) -> str:
    """Локализованная подпись статуса нагрузки по ключу status.*."""
    return t(label_key, lang)
